#!/usr/bin/env node
// Concatenates the chatbot modules into chatbot/chatbot.bundle.js (one request per page).
// Edit the modular sources in chatbot/ and chatbot/data/, then run:  node scripts/build-chatbot.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "chatbot");
const dataOrder = ["knowledge.js", "greetings.js", "faq.js", "services-qa.js", "business-qa.js", "pricing-contact.js", "smalltalk.js", "extra-qa.js", "fallback.js"];
const dataFiles = readdirSync(join(ROOT, "data")).filter((f) => f.endsWith(".js"));
const ordered = [...dataOrder.filter((f) => dataFiles.includes(f)), ...dataFiles.filter((f) => !dataOrder.includes(f)).sort()];
const parts = [...ordered.map((f) => "data/" + f), "util.js", "context.js", "engine.js", "leadflow.js", "provider.js", "ui.js"];
const out = parts.map((p) => `/* ---- ${p} ---- */\n${readFileSync(join(ROOT, p), "utf8")}`).join("\n;\n");
writeFileSync(join(ROOT, "chatbot.bundle.js"), `/* GURU AI assistant bundle. Generated by scripts/build-chatbot.mjs. Do not edit. */\n${out}\n`);
console.log(`chatbot.bundle.js: ${parts.length} modules, ${(out.length / 1024).toFixed(0)} KB`);
